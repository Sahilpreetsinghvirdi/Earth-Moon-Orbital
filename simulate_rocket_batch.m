function [flightResults, trajectorySample] = simulate_rocket_batch(config, inputs, sampleIndices)
n = config.launchCount;
dt = config.timeStep_s;
maxSteps = ceil(config.maxFlightTime_s / dt);
g0 = config.g0_mps2;
angles_rad = deg2rad(inputs.launchAngle_deg);
thrustX_N = inputs.thrust_N .* cos(angles_rad);
thrustY_N = inputs.thrust_N .* sin(angles_rad);
x_m = zeros(n, 1);
y_m = config.initialAltitude_m .* ones(n, 1);
vx_mps = zeros(n, 1);
vy_mps = zeros(n, 1);
fuel_kg = inputs.propellantMass_kg;
active = true(n, 1);
impactOccurred = false(n, 1);
numericalFailure = false(n, 1);
timedOut = false(n, 1);
apogee_m = y_m;
maximumVelocity_mps = zeros(n, 1);
maximumAcceleration_mps2 = zeros(n, 1);
maximumDynamicPressure_Pa = zeros(n, 1);
fuelConsumed_kg = zeros(n, 1);
burnoutTime_s = nan(n, 1);
impactTime_s = nan(n, 1);
impactDownrange_m = nan(n, 1);
impactAltitude_m = nan(n, 1);
impactVelocityX_mps = nan(n, 1);
impactVelocityY_mps = nan(n, 1);
impactSpeed_mps = nan(n, 1);
impactFlightPathAngle_deg = nan(n, 1);
impactDynamicPressure_Pa = nan(n, 1);
finalX_m = nan(n, 1);
finalY_m = nan(n, 1);
finalVx_mps = nan(n, 1);
finalVy_mps = nan(n, 1);
sampleIndices = sampleIndices(:);
sampleCount = numel(sampleIndices);
trajectorySample = struct;
trajectorySample.indices = sampleIndices;
trajectorySample.time_s = (0:maxSteps)' .* dt;
trajectorySample.downrange_m = nan(maxSteps + 1, sampleCount);
trajectorySample.altitude_m = nan(maxSteps + 1, sampleCount);
trajectorySample.velocity_mps = nan(maxSteps + 1, sampleCount);
trajectorySample.acceleration_mps2 = nan(maxSteps + 1, sampleCount);
trajectorySample.dynamicPressure_Pa = nan(maxSteps + 1, sampleCount);
trajectorySample.active = false(maxSteps + 1, sampleCount);
trajectorySample.downrange_m(1, :) = x_m(sampleIndices);
trajectorySample.altitude_m(1, :) = y_m(sampleIndices);
trajectorySample.velocity_mps(1, :) = 0;
trajectorySample.acceleration_mps2(1, :) = 0;
trajectorySample.dynamicPressure_Pa(1, :) = 0;
trajectorySample.active(1, :) = true;
progressStep = max(1, ceil(maxSteps / config.progressIntervals));
for step = 1:maxSteps
    t_s = (step - 1) * dt;
    if ~any(active)
        break
    end
    activeAtStart = active;
    altitudeForModel_m = max(y_m, 0);
    mass_kg = inputs.dryMass_kg + fuel_kg;
    rho_kgpm3 = config.referenceDensity_kgpm3 .* inputs.densityMultiplier .* (config.nominalTemperature_K ./ inputs.temperature_K) .* exp(-altitudeForModel_m ./ inputs.scaleHeight_m);
    airVx_mps = vx_mps - inputs.windSpeed_mps;
    airVy_mps = vy_mps;
    airSpeed_mps = hypot(airVx_mps, airVy_mps);
    dynamicPressure_Pa = 0.5 .* rho_kgpm3 .* airSpeed_mps .^ 2;
    dragFactor_Nspm = dynamicPressure_Pa .* inputs.dragCoefficient .* inputs.referenceArea_m2 ./ max(airSpeed_mps, 1e-9);
    dragX_N = -dragFactor_Nspm .* airVx_mps;
    dragY_N = -dragFactor_Nspm .* airVy_mps;
    poweredFraction = double(active) .* min(1, fuel_kg ./ (inputs.burnRate_kgps .* dt));
    accelerationX_mps2 = (thrustX_N .* poweredFraction + dragX_N) ./ mass_kg;
    gravity_mps2 = g0 .* (config.earthRadius_m ./ (config.earthRadius_m + altitudeForModel_m)) .^ 2;
    accelerationY_mps2 = (thrustY_N .* poweredFraction + dragY_N) ./ mass_kg - gravity_mps2;
    accelerationMagnitude_mps2 = hypot(accelerationX_mps2, accelerationY_mps2);
    maximumDynamicPressure_Pa(active) = max(maximumDynamicPressure_Pa(active), dynamicPressure_Pa(active));
    maximumAcceleration_mps2(active) = max(maximumAcceleration_mps2(active), accelerationMagnitude_mps2(active));
    maximumVelocity_mps(active) = max(maximumVelocity_mps(active), hypot(vx_mps(active), vy_mps(active)));
    xNext_m = x_m + vx_mps .* dt + 0.5 .* accelerationX_mps2 .* dt ^ 2;
    yNext_m = y_m + vy_mps .* dt + 0.5 .* accelerationY_mps2 .* dt ^ 2;
    vxNext_mps = vx_mps + accelerationX_mps2 .* dt;
    vyNext_mps = vy_mps + accelerationY_mps2 .* dt;
    fuelNext_kg = max(0, fuel_kg - inputs.burnRate_kgps .* poweredFraction .* dt);
    justBurnedOut = active & isnan(burnoutTime_s) & fuel_kg > 0 & fuelNext_kg <= 0;
    burnoutTime_s(justBurnedOut) = t_s + dt .* fuel_kg(justBurnedOut) ./ inputs.burnRate_kgps(justBurnedOut);
    validState = isfinite(xNext_m) & isfinite(yNext_m) & isfinite(vxNext_mps) & isfinite(vyNext_mps) & isfinite(fuelNext_kg);
    badState = active & ~validState;
    if any(badState)
        numericalFailure(badState) = true;
        active(badState) = false;
        finalX_m(badState) = x_m(badState);
        finalY_m(badState) = y_m(badState);
        finalVx_mps(badState) = vx_mps(badState);
        finalVy_mps(badState) = vy_mps(badState);
    end
    potentialImpact = active & y_m > 0 & yNext_m <= 0 & vyNext_mps < 0;
    if any(potentialImpact)
        interpolation = y_m(potentialImpact) ./ (y_m(potentialImpact) - yNext_m(potentialImpact));
        interpolation = min(max(interpolation, 0), 1);
        impactedIndices = find(potentialImpact);
        impactOccurred(impactedIndices) = true;
        impactTime_s(impactedIndices) = t_s + interpolation .* dt;
        impactDownrange_m(impactedIndices) = x_m(impactedIndices) + interpolation .* (xNext_m(impactedIndices) - x_m(impactedIndices));
        impactAltitude_m(impactedIndices) = 0;
        impactVelocityX_mps(impactedIndices) = vx_mps(impactedIndices) + interpolation .* (vxNext_mps(impactedIndices) - vx_mps(impactedIndices));
        impactVelocityY_mps(impactedIndices) = vy_mps(impactedIndices) + interpolation .* (vyNext_mps(impactedIndices) - vy_mps(impactedIndices));
        impactSpeed_mps(impactedIndices) = hypot(impactVelocityX_mps(impactedIndices), impactVelocityY_mps(impactedIndices));
        impactFlightPathAngle_deg(impactedIndices) = atan2d(impactVelocityY_mps(impactedIndices), impactVelocityX_mps(impactedIndices));
        impactAirVx_mps = impactVelocityX_mps(impactedIndices) - inputs.windSpeed_mps(impactedIndices);
        impactAirSpeed_mps = hypot(impactAirVx_mps, impactVelocityY_mps(impactedIndices));
        impactDynamicPressure_Pa(impactedIndices) = 0.5 .* config.referenceDensity_kgpm3 .* inputs.densityMultiplier(impactedIndices) .* (config.nominalTemperature_K ./ inputs.temperature_K(impactedIndices)) .* impactAirSpeed_mps .^ 2;
        maximumDynamicPressure_Pa(impactedIndices) = max(maximumDynamicPressure_Pa(impactedIndices), impactDynamicPressure_Pa(impactedIndices));
        maximumVelocity_mps(impactedIndices) = max(maximumVelocity_mps(impactedIndices), impactSpeed_mps(impactedIndices));
        finalX_m(impactedIndices) = impactDownrange_m(impactedIndices);
        finalY_m(impactedIndices) = 0;
        finalVx_mps(impactedIndices) = impactVelocityX_mps(impactedIndices);
        finalVy_mps(impactedIndices) = impactVelocityY_mps(impactedIndices);
        xNext_m(impactedIndices) = impactDownrange_m(impactedIndices);
        yNext_m(impactedIndices) = 0;
        vxNext_mps(impactedIndices) = impactVelocityX_mps(impactedIndices);
        vyNext_mps(impactedIndices) = impactVelocityY_mps(impactedIndices);
        active(impactedIndices) = false;
    end
    advancing = active;
    x_m(advancing) = xNext_m(advancing);
    y_m(advancing) = yNext_m(advancing);
    vx_mps(advancing) = vxNext_mps(advancing);
    vy_mps(advancing) = vyNext_mps(advancing);
    fuel_kg(advancing) = fuelNext_kg(advancing);
    apogee_m(advancing) = max(apogee_m(advancing), y_m(advancing));
    fuelConsumed_kg = inputs.propellantMass_kg - fuel_kg;
    sampledValid = activeAtStart(sampleIndices) & ~badState(sampleIndices);
    trajectorySample.downrange_m(step + 1, sampledValid) = xNext_m(sampleIndices(sampledValid));
    trajectorySample.altitude_m(step + 1, sampledValid) = yNext_m(sampleIndices(sampledValid));
    trajectorySample.velocity_mps(step + 1, sampledValid) = hypot(vxNext_mps(sampleIndices(sampledValid)), vyNext_mps(sampleIndices(sampledValid)));
    trajectorySample.acceleration_mps2(step + 1, sampledValid) = accelerationMagnitude_mps2(sampleIndices(sampledValid));
    trajectorySample.dynamicPressure_Pa(step + 1, sampledValid) = dynamicPressure_Pa(sampleIndices(sampledValid));
    trajectorySample.active(step + 1, sampledValid) = active(sampleIndices(sampledValid));
    if config.showProgress && (mod(step, progressStep) == 0 || step == maxSteps)
        fprintf('Simulation progress: %5.1f%%, active launches: %d\n', 100 * step / maxSteps, nnz(active));
    end
end
if any(active)
    timedOut(active) = true;
    finalX_m(active) = x_m(active);
    finalY_m(active) = y_m(active);
    finalVx_mps(active) = vx_mps(active);
    finalVy_mps(active) = vy_mps(active);
end
flightResults = struct;
flightResults.apogee_m = apogee_m;
flightResults.maximumVelocity_mps = maximumVelocity_mps;
flightResults.maximumAcceleration_mps2 = maximumAcceleration_mps2;
flightResults.maximumDynamicPressure_Pa = maximumDynamicPressure_Pa;
flightResults.fuelConsumed_kg = fuelConsumed_kg;
flightResults.remainingFuel_kg = fuel_kg;
flightResults.burnoutTime_s = burnoutTime_s;
flightResults.impactOccurred = impactOccurred;
flightResults.numericalFailure = numericalFailure;
flightResults.timedOut = timedOut;
flightResults.flightTime_s = impactTime_s;
flightResults.downrange_m = impactDownrange_m;
flightResults.impactAltitude_m = impactAltitude_m;
flightResults.impactVelocityX_mps = impactVelocityX_mps;
flightResults.impactVelocityY_mps = impactVelocityY_mps;
flightResults.impactSpeed_mps = impactSpeed_mps;
flightResults.impactFlightPathAngle_deg = impactFlightPathAngle_deg;
flightResults.impactDynamicPressure_Pa = impactDynamicPressure_Pa;
flightResults.finalX_m = finalX_m;
flightResults.finalY_m = finalY_m;
flightResults.finalVelocity_mps = hypot(finalVx_mps, finalVy_mps);
flightResults.finalVx_mps = finalVx_mps;
flightResults.finalVy_mps = finalVy_mps;
end
